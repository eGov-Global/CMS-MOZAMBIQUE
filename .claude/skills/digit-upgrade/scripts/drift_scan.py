#!/usr/bin/env python3
"""List files in a live DIGIT deploy dir that are not identical to a repo checkout.

Read-only. Usage:
  python3 -I drift_scan.py --live /opt/digit --repo ~/CMS-MOZAMBIQUE
"""
import argparse
import difflib
import filecmp
import os

SKIP_DIRS = {".openbao", ".build", "node_modules", ".git", "dist", "__pycache__"}
SKIP_EXT = (".jar", ".pyc")
# Files deploy.sh writes/patches itself; a diff here is expected, but review it
# for hand edits (compose) - the rest are rebuilt from host_vars every run.
GENERATED = {".env", "docker-compose.egov-digit.yaml", "nginx/globalConfigs.js", "nginx/digit-ui.conf"}


def walk(root):
    for base, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for f in files:
            if not f.endswith(SKIP_EXT):
                yield os.path.join(base, f)


def changed_lines(a, b):
    try:
        x = open(a, errors="replace").read().splitlines()
        y = open(b, errors="replace").read().splitlines()
    except OSError:
        return "?"
    return sum(1 for l in difflib.unified_diff(x, y, lineterm="", n=0)
               if l[:1] in "+-" and not l.startswith(("+++", "---")))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--live", default="/opt/digit")
    ap.add_argument("--repo", required=True)
    args = ap.parse_args()

    by_name = {}
    for p in walk(args.repo):
        by_name.setdefault(os.path.basename(p), []).append(p)

    same, rows = 0, []
    for p in walk(args.live):
        rel = os.path.relpath(p, args.live)
        name = os.path.basename(p)
        if name.endswith(".progress"):
            continue
        direct = [os.path.join(args.repo, "local-setup", rel), os.path.join(args.repo, rel),
                  os.path.join(args.repo, "local-setup/ansible/files", rel)]
        candidates = [c for c in direct if os.path.isfile(c)] + by_name.get(name, [])
        if any(filecmp.cmp(p, c, shallow=False) for c in candidates):
            same += 1
            continue
        if not candidates:
            rows.append(("ONLY ON SERVER", rel, ""))
            continue
        kind = "GENERATED BY DEPLOY" if rel in GENERATED else "CHANGED"
        rows.append((kind, rel, f"{changed_lines(candidates[0], p)} lines vs {os.path.relpath(candidates[0], args.repo)}"))

    print(f"identical: {same}  differing: {len(rows)}")
    for r in sorted(rows):
        print(" | ".join(x for x in r if x))


if __name__ == "__main__":
    main()
